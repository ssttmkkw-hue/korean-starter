  '像学校里上课一样，每一课围绕一两个语法点展开：先讲形式和规则，再讲用法和易错点，然后用单词和会话把它用起来，最后做练习巩固。后面的课会反复用到前面学过的语法，建议按顺序学；当然你也可以随时跳到想看的那一课。'

// 练习用到的朗读文本（和 UI 里保持一致，生成语音时也用它）
export function exerciseAudio(ex) {
  if (ex.type === 'choice') return ex.say || ex.q.replace('___', ex.options[ex.answer])
  if (ex.type === 'order') return ex.answers[0]
  return ex.ko
}

